#!/usr/bin/env python3
"""Phase 0 data checks: does anything leak between the splits, and what does each split hold?

uv run data/check_dataset.py   # prints the report and writes it to docs/data-checks.md

Rerun after every dataset build. Exits with code 1 if a check fails.
"""

import io
import json
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import imagehash
import numpy as np
import polars as pl
from PIL import Image
from setup_dataset import BUILD, RAW, ROOT, read_crowd_csv, read_labels

REPORT = ROOT.parent / "docs" / "data-checks.md"
SPLITS = ["fit", "val", "pool", "holdout"]
CROWD_CSV = RAW / "ham10000" / "ISIC2018_Task3_Test_NatureMedicine_AI_Interaction_Benefit.csv"
EASTER_EGG = "ISIC_0035068"  # the one test image Barata et al. 2023 left out of their analysis

# Two images are near-duplicates if their 256-bit perceptual hashes differ in at most this many bits.
# The report measures how far a resized, re-encoded copy moves, so the threshold is checked on every run.
NEAR_DUP_BITS = 24


# --- report ----------------------------------------------------------------

lines: list[str] = []  # the report, as markdown
checks: list[tuple[bool, str]] = []  # (passed, text) of every pass/fail check


def write(text: str = "") -> None:
    lines.append(text)


def heading(text: str) -> None:
    write(text)
    write()


def check(passed: bool, text: str) -> None:
    """One pass/fail line. Any fail makes the script exit with code 1."""
    write(f"- **{'PASS' if passed else 'FAIL'}** {text}")
    checks.append((passed, text))


def table(df: pl.DataFrame) -> None:
    if lines[-1]:  # a table needs a blank line before it
        write()
    with pl.Config(
        tbl_formatting="MARKDOWN",
        tbl_hide_column_data_types=True,
        tbl_hide_dataframe_shape=True,
        tbl_rows=-1,
        tbl_cols=-1,
        tbl_width_chars=1000,
        fmt_str_lengths=100,
        thousands_separator=",",
    ):
        write(str(df))
    write()


def raw_missing(*paths: Path) -> bool:
    """True, with a note in the report, if a raw file this check needs is not there."""
    missing = [path for path in paths if not path.exists()]
    if missing:
        write(f"Skipped: `{missing[0].relative_to(ROOT)}` not found. Run `uv run data/setup_dataset.py fetch` first.")
    return bool(missing)


def counts_per_split(items: pl.DataFrame, column: str) -> pl.DataFrame:
    """Number of images per value of `column` (rows) and split (columns)."""
    return (
        items.group_by(column, "split")
        .len()
        .pivot(on="split", index=column, values="len")
        .select(column, *SPLITS)
        .with_columns(pl.col(SPLITS).fill_null(0))
        .with_columns(total=pl.sum_horizontal(SPLITS))
        .sort(column, nulls_last=True)
    )


# --- overview --------------------------------------------------------------


def overview(items: pl.DataFrame) -> None:
    build = json.loads((BUILD / "BUILD.json").read_text())
    commit = (build.get("git_commit") or "unknown")[:7]
    per_split = dict(items["split"].value_counts().iter_rows())

    heading("# Data checks (phase 0)")
    write("Written by `data/check_dataset.py`. Rerun the script after every dataset build; do not edit this file.")
    write()
    write(f"- Build checked: `BUILD.json` of {build['built_utc']}, built by `setup_dataset.py` at commit `{commit}`.")
    write(
        f"- Images per split: {' · '.join(f'{split} {per_split[split]:,}' for split in SPLITS)} (total {len(items):,})."
    )
    write()


# --- 0.1 lesion overlap ----------------------------------------------------


def check_lesion_overlap(items: pl.DataFrame) -> None:
    heading("## 0.1 Lesion overlap")
    table(
        items.group_by("split_source").agg(images=pl.len(), lesions=pl.col("lesion_id").n_unique()).sort("split_source")
    )

    train_lesions = set(items.filter(pl.col("split_source") == "ham_train")["lesion_id"])
    test_lesions = set(items.filter(pl.col("split_source") == "isic_test")["lesion_id"])
    shared = train_lesions & test_lesions
    spread = items.group_by("lesion_id").agg(pl.col("split").n_unique()).filter(pl.col("split") > 1)

    check(items["lesion_id"].null_count() == 0, f"{items['lesion_id'].null_count()} images have no `lesion_id`")
    check(not shared, f"{len(shared)} lesions occur in both `ham_train` and `isic_test`")
    check(spread.is_empty(), f"{spread.height} lesions are spread over more than one split")
    write()


# --- 0.2 duplicate images --------------------------------------------------


def describe_cassidy_lists(items: pl.DataFrame) -> None:
    heading("### Cassidy et al. 2022 lists")
    lists = sorted((RAW / "cassidy2022").glob("*.txt"))
    if raw_missing(RAW / "cassidy2022") or not lists:
        return

    train_ids = items.filter(pl.col("split_source") == "ham_train")["image_id"].to_list()
    test_ids = items.filter(pl.col("split_source") == "isic_test")["image_id"].to_list()
    rows = []
    for path in lists:
        for line in path.read_text().splitlines():
            year, part = Path(line).parts[5:7]  # /home/bc/Datasets/ISIC (B)/2018/train/<folder>/ISIC_0024306.jpg
            rows.append({"list": path.name[:2], "release": f"{year} {part}", "image_id": Path(line).stem})
    listed = pl.DataFrame(rows)

    table(
        listed.group_by("list", "release")
        .agg(
            listed=pl.len(),
            our_ham_train=pl.col("image_id").is_in(train_ids).sum(),
            our_isic_test=pl.col("image_id").is_in(test_ids).sum(),
        )
        .sort("list", "release")
    )
    write(
        "List 06 is `all_train_duplicates_deleted_(all but newest)`, list 12 is `all_test_duplicates_deleted_(...)`. "
        "Each names the files deleted when the ISIC releases 2016 to 2020 were merged and de-duplicated with FSlint, "
        "keeping the newest copy of each group. A line names the deleted file only, never the file it duplicates, "
        "so the lists hold no pairs. They name every ISIC 2018 image on both sides, presumably because newer releases "
        "ship the same files again (HAM10000 is part of the ISIC 2019 training set). Being listed therefore says "
        "nothing about a link between our train and test images; the perceptual hash below answers that. "
        "Cassidy's train-vs-test lists (07 to 11, not fetched) cover only the 2016 and 2017 test sets."
    )
    write()


def perceptual_hash(image_file) -> np.ndarray:
    """256-bit perceptual hash (DCT). The JPEG is decoded at reduced size: much faster, and the same for every image."""
    with Image.open(image_file) as image:
        image.draft("L", (128, 128))
        return imagehash.phash(image, hash_size=16).hash.flatten()


def hash_of_altered_copy(path: Path) -> np.ndarray:
    """Hash of the image after resizing it to 75 % and re-saving it at JPEG quality 70: a near-duplicate on purpose."""
    with Image.open(path) as image:
        copy = io.BytesIO()
        image.resize((image.width * 3 // 4, image.height * 3 // 4)).save(copy, "JPEG", quality=70)
    copy.seek(0)
    return perceptual_hash(copy)


def hamming_distances(bits: np.ndarray) -> np.ndarray:
    """Distance between every two packed hashes (n x n), computed in blocks of rows to save memory."""
    blocks = [
        np.bitwise_count(bits[start : start + 256, None] ^ bits[None]).sum(axis=-1, dtype=np.uint16)
        for start in range(0, len(bits), 256)
    ]
    return np.vstack(blocks)


def closest_pair(items: pl.DataFrame, dist: np.ndarray, allowed: np.ndarray) -> str:
    """The closest pair among the allowed ones, as one line of text."""
    a, b = np.unravel_index(np.argmin(np.where(allowed, dist, 999)), dist.shape)
    image_a, image_b = items[int(a)], items[int(b)]
    return (
        f"`{image_a['image_id'][0]}` ({image_a['dx'][0]}, {image_a['split'][0]}) and "
        f"`{image_b['image_id'][0]}` ({image_b['dx'][0]}, {image_b['split'][0]}), {dist[a, b]} bits apart"
    )


def check_near_duplicates(items: pl.DataFrame) -> None:
    heading("### Near-duplicates by perceptual hash")
    write(
        "Every image gets a 256-bit perceptual hash; two images whose hashes differ in at most "
        f"{NEAR_DUP_BITS} bits count as near-duplicates. This also finds resized or re-encoded copies, "
        "not only byte-identical files."
    )
    write()
    paths = [BUILD / path for path in items["image_path"]]
    with ProcessPoolExecutor() as workers:
        hashes = np.array(list(workers.map(perceptual_hash, paths, chunksize=64)))
        copies = np.array(list(workers.map(hash_of_altered_copy, paths[:200], chunksize=8)))

    copy_bits = (copies != hashes[:200]).sum(axis=1)
    check(
        copy_bits.max() <= NEAR_DUP_BITS,
        f"the threshold of {NEAR_DUP_BITS} of 256 bits catches altered copies: resized to 75 % and re-saved at "
        f"JPEG quality 70, an image moves by at most {copy_bits.max()} bits (median {np.median(copy_bits):.0f}, "
        f"{len(copy_bits)} images)",
    )

    dist = hamming_distances(np.packbits(hashes, axis=1))
    a, b = np.nonzero(np.triu(dist <= NEAR_DUP_BITS, k=1))  # every pair once
    columns = ["image_id", "lesion_id", "dx", "split"]
    pairs = (
        items[a]
        .select(pl.col(columns).name.suffix("_a"))
        .hstack(items[b].select(pl.col(columns).name.suffix("_b")))
        .with_columns(bits=pl.Series(dist[a, b]))
    )
    same_lesion = pairs.filter(pl.col("lesion_id_a") == pl.col("lesion_id_b"))
    other_lesion = pairs.filter(pl.col("lesion_id_a") != pl.col("lesion_id_b"))
    across_splits = pairs.filter(pl.col("split_a") != pl.col("split_b"))

    write(
        f"- {pairs.height} near-duplicate pairs among all {len(items):,} images; "
        f"{same_lesion.height} of them are two photos of the same lesion."
    )
    check(across_splits.is_empty(), f"{across_splits.height} near-duplicate pairs have their images in two splits")
    if not across_splits.is_empty():
        table(across_splits)

    source = items["split_source"].to_numpy()
    split = items["split"].to_numpy()
    write(f"- Closest pair across `ham_train` and `isic_test`: {closest_pair(items, dist, source[:, None] != source)}.")
    write(f"- Closest pair in two different splits: {closest_pair(items, dist, split[:, None] != split)}.")
    write(
        f"- Pairs with two different `lesion_id` values: {other_lesion.height}. "
        "Harmless while both images sit in the same split, but the lesion grouping missed them."
    )
    if other_lesion.is_empty():
        write()
    else:
        table(other_lesion)


def check_duplicate_images(items: pl.DataFrame) -> None:
    heading("## 0.2 Duplicate images")
    describe_cassidy_lists(items)
    check_near_duplicates(items)


# --- 0.3 dropped test images and the easter egg ----------------------------


def check_dropped_test_images(items: pl.DataFrame, trials: pl.DataFrame) -> None:
    heading("## 0.3 Dropped test images and the easter egg")
    if raw_missing(RAW / "isic2018", CROWD_CSV):
        return

    test = read_labels().filter(pl.col("split_source") == "isic_test")
    voted = read_crowd_csv(CROWD_CSV)["image_id"].to_list()
    dropped = test.filter(~pl.col("image_id").is_in(items["image_id"].to_list()))
    dropped_with_votes = dropped.filter(pl.col("image_id").is_in(voted)).height
    kept_test = items.filter(pl.col("split_source") == "isic_test")
    unanimous = kept_test.filter(pl.col("n_raters").is_null()).height
    dropped_classes = ", ".join(f"{dx} {n}" for dx, n in dropped["dx"].value_counts().sort("dx").iter_rows())
    dropped_with_trials = dropped.filter(pl.col("image_id").is_in(trials["image_id"].to_list())).height
    trials_without_item = trials.filter(~pl.col("image_id").is_in(items["image_id"].to_list()))

    write(f"- ISIC 2018 test set: {test.height:,} images. {dropped.height} are not in `items` ({dropped_classes}).")
    check(
        dropped_with_votes == 0,
        f"{dropped_with_votes} dropped images appear in the crowd file "
        "(expected 0: they were dropped for having no votes, not for being unanimous)",
    )
    check(
        kept_test["d_human"].null_count() == 0,
        f"{kept_test['d_human'].null_count()} kept test images have no `d_human`",
    )
    write(f"- {unanimous} kept test images are unanimous (`n_raters` is null, `d_human` is set).")
    write(
        f"- {dropped_with_trials} dropped images have reader trials: {trials_without_item.height} rows of "
        f"`reader_trials` point to {trials_without_item['image_id'].n_unique()} images that are not in `items`."
    )

    egg_label = test.filter(pl.col("image_id") == EASTER_EGG)
    egg_item = items.filter(pl.col("image_id") == EASTER_EGG)
    write()
    write(f"`{EASTER_EGG}`, the image Barata et al. 2023 left out:")
    write()
    write(f"- In the ISIC 2018 test ground truth: {'yes, dx ' + egg_label['dx'][0] if egg_label.height else 'no'}.")
    write(f"- Has crowd votes: {'yes' if EASTER_EGG in voted else 'no'}.")
    write(
        f"- In `items`: {'yes, split ' + egg_item['split'][0] if egg_item.height else 'no (dropped: no crowd votes)'}."
    )
    write(f"- Rows in `reader_trials`: {trials.filter(pl.col('image_id') == EASTER_EGG).height}.")
    write()


# --- 0.4 to 0.6 what the splits hold ----------------------------------------


def check_label_provenance(items: pl.DataFrame) -> None:
    heading("## 0.4 Label provenance (`dx_type`)")
    missing = items.filter(pl.col("split_source") == "isic_test")["dx_type"].null_count()
    check(missing == 0, f"{missing} test images have no `dx_type`")
    table(counts_per_split(items, "dx_type"))


def check_class_mix(items: pl.DataFrame) -> None:
    heading("## 0.5 Class mix per split (`dx`)")
    table(counts_per_split(items, "dx"))


def check_reader_coverage(items: pl.DataFrame, trials: pl.DataFrame) -> None:
    heading("## 0.6 Reader coverage (`reader_trials`, Barata 2023)")
    write("A session shows an image twice (unaided, then aided). Counts are sessions per image, over covered images.")
    sessions = trials.group_by("image_id").agg(sessions=pl.col("session_id").n_unique())
    table(
        items.filter(pl.col("split").is_in(["pool", "holdout"]))
        .join(sessions, on="image_id", how="left")
        .group_by("split")
        .agg(
            images=pl.len(),
            with_trials=pl.col("sessions").is_not_null().sum(),
            sessions_min=pl.col("sessions").min(),
            sessions_median=pl.col("sessions").median(),
            sessions_max=pl.col("sessions").max(),
        )
        .with_columns(with_trials_pct=(100 * pl.col("with_trials") / pl.col("images")).round(1))
        .sort("split", descending=True)  # pool, holdout
    )


# --- main ------------------------------------------------------------------


def summary() -> None:
    failed = [text for passed, text in checks if not passed]
    heading("## Summary")
    write(f"{len(checks) - len(failed)} of {len(checks)} checks pass.")
    for text in failed:
        write(f"- FAIL: {text}")


def main() -> None:
    start = time.time()
    items = pl.read_parquet(BUILD / "tables" / "items.parquet")
    trials = pl.read_parquet(BUILD / "tables" / "reader_trials.parquet")

    overview(items)
    check_lesion_overlap(items)
    check_duplicate_images(items)
    check_dropped_test_images(items, trials)
    check_label_provenance(items)
    check_class_mix(items)
    check_reader_coverage(items, trials)
    summary()

    report = "\n".join(lines) + "\n"
    print(report)
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text(report)
    print(f"wrote {REPORT.relative_to(ROOT.parent)} in {time.time() - start:.0f} s")
    sys.exit(1 if any(not passed for passed, _ in checks) else 0)


if __name__ == "__main__":
    main()
